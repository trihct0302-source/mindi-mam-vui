"""Generate accessory envelopes and conservative edge trims from the shipped sprites."""
from collections import defaultdict
from pathlib import Path
from statistics import median
import json

from PIL import Image, ImageSequence

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets'
OUTPUT = ASSETS / 'ui-v1' / 'accessory-anchors.js'


def quantile(histogram, portion):
    target = sum(histogram) * portion
    count = 0
    for coordinate, weight in enumerate(histogram):
        count += weight
        if count >= target:
            return coordinate
    raise ValueError('No visible pixels')


def envelope(alpha, top, bottom):
    width, height = alpha.size
    xs, ys = [0] * width, [0] * height
    pixels = alpha.load()
    for y in range(top, bottom):
        for x in range(width):
            if pixels[x, y] >= 128:
                xs[x] += 1
                ys[y] += 1
    if not sum(xs):
        raise ValueError('Empty sprite frame')
    return [100 * quantile(xs, 0.03) / width, 100 * quantile(ys, 0.02) / height,
            100 * quantile(xs, 0.97) / width, 100 * quantile(ys, 0.98) / height]


def visible_bands(alpha):
    width, height = alpha.size
    pixels = alpha.load()
    bands = []
    start = None
    for y in range(height + 1):
        visible = y < height and any(pixels[x, y] for x in range(width))
        if visible and start is None:
            start = y
        elif not visible and start is not None:
            bands.append((start, y))
            start = None
    return bands


def common_trim(frames):
    # Only trim whole, visibly separate strips across every frame. Keep the
    # subject and nearby effects even when they touch an outer strip.
    top = 0
    bottom = frames[0].height
    limits = {'top': [], 'bottom': []}
    for frame in frames:
        bands = visible_bands(frame)
        main = max(bands, key=lambda band: band[1] - band[0])
        height = main[1] - main[0]
        strip_limit = max(2, height * 0.15)
        upper = [band for band in bands if band[1] < main[0]]
        lower = [band for band in bands if band[0] > main[1]]
        if upper and all(b - a <= strip_limit for a, b in upper):
            limits['top'].append((upper[-1][1], main[0]))
        if lower and all(b - a <= strip_limit for a, b in lower):
            limits['bottom'].append((main[1], lower[0][0]))
    if len(limits['top']) == len(frames):
        remove_until = max(a for a, _ in limits['top'])
        keep_from = min(b for _, b in limits['top'])
        if remove_until <= keep_from:
            top = remove_until
    if len(limits['bottom']) == len(frames):
        keep_until = max(a for a, _ in limits['bottom'])
        remove_from = min(b for _, b in limits['bottom'])
        if keep_until <= remove_from:
            bottom = remove_from
    return top, bottom


forms = defaultdict(dict)
trims = {}
for original in sorted((ASSETS / 'animations').glob('*/*.gif')) + sorted((ASSETS / 'characters').glob('*.png')):
    override = ASSETS / 'qa-v151' / original.relative_to(ASSETS)
    state = 'portrait' if original.suffix == '.png' else original.parent.name
    with Image.open(override if override.exists() else original) as image:
        alphas = [frame.convert('RGBA').getchannel('A') for frame in ImageSequence.Iterator(image)]
        # V8 uses intentionally isolated effects. Only apply the automatic
        # strip rule to the uniform idle bob frames from the V4 sheets.
        top, bottom = (common_trim(alphas) if state in {'idle', 'portrait'} and not original.stem.startswith('aries_')
                       else (0, image.height))
        frames = [envelope(alpha, top, bottom) for alpha in alphas]
        if top or bottom != image.height:
            trims[f'{original.stem}/{state}'] = [round(100 * top / image.height, 5),
                                    round(100 * (image.height - bottom) / image.height, 5)]
    forms[original.stem][state] = [round(median(axis), 1) for axis in zip(*frames)]

assert len(forms) == 48 and all(len(states) == 6 for states in forms.values())
OUTPUT.write_text('// Generated by scripts/measure_accessory_anchors.py.\nexport const envelopes = ' +
                  json.dumps(forms, separators=(',', ':')) + ';\nexport const spriteTrims = ' +
                  json.dumps(trims, separators=(',', ':')) + ';\n', encoding='utf-8')
print(f'{len(forms)} forms, {sum(map(len, forms.values()))} envelopes, {len(trims)} safe trims')
