"""Measure per-form placement envelopes from alpha coverage in the idle sprites."""
from pathlib import Path
from statistics import median
import json

from PIL import Image, ImageSequence

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets'
OUTPUT = ASSETS / 'ui-v1' / 'accessory-anchors.js'


def quantile(histogram, portion):
    target = sum(histogram) * portion
    count = 0
    for coordinate, weight in enumerate(histogram):
        count += weight
        if count >= target:
            return coordinate
    raise ValueError('No nontransparent pixels')


def envelope(frame):
    rgba = frame.convert('RGBA')
    width, height = rgba.size
    xs, ys = [0] * width, [0] * height
    for i, alpha in enumerate(rgba.getchannel('A').getdata()):
        if alpha >= 128:
            xs[i % width] += 1
            ys[i // width] += 1
    if not sum(xs):
        raise ValueError('Empty sprite frame')
    return [100 * quantile(xs, 0.03) / width, 100 * quantile(ys, 0.02) / height,
            100 * quantile(xs, 0.97) / width, 100 * quantile(ys, 0.98) / height]


forms = {}
for original in sorted((ASSETS / 'animations' / 'idle').glob('*.gif')):
    override = ASSETS / 'qa-v151' / original.relative_to(ASSETS)
    with Image.open(override if override.exists() else original) as image:
        frames = [envelope(frame) for frame in ImageSequence.Iterator(image)]
    forms[original.stem] = [round(median(axis), 1) for axis in zip(*frames)]

assert len(forms) == 48
OUTPUT.write_text('// Generated by scripts/measure_accessory_anchors.py.\nexport const envelopes = ' +
                  json.dumps(forms, separators=(',', ':')) + ';\n', encoding='utf-8')
