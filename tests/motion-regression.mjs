import assert from 'node:assert/strict';
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
const dir = process.argv[2] ?? fileURLToPath(new URL('..',import.meta.url));
const source = fs.readFileSync(dir+'/assets/ui-v1/motion-system-v3.js','utf8');
const {MindiMotion} = await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
globalThis.window={matchMedia:()=>({matches:false})};
globalThis.CustomEvent=class{constructor(_,options){this.detail=options.detail}};
const node=()=>({classList:{add(){},remove(){}},dataset:{},remove(){},append(){}});
globalThis.document={createElement:node};
const events=[];
const root={...node(),querySelector:()=>null,querySelectorAll:()=>[],addEventListener(){},removeEventListener(){},dispatchEvent:e=>events.push(e.detail)};
const motion=new MindiMotion({root,characterEl:node()});
await motion.play('character.evolve',{fromLevel:4,toLevel:4});
assert.deepEqual(events.map(x=>x.name),['blocked']);
events.length=0;
const stale=motion.play('character.evolve',{fromLevel:1,toLevel:2});
await motion.play('character.idle',{level:3});
await stale;
assert.deepEqual(events.filter(x=>x.name==='complete').map(x=>x.motion),['character.idle']);
assert.match(motion.characterEl.src, /aries_lv3.gif$/);
const transition=motion.play('screen.transition');
await motion.play('loading.hide');
await transition;
assert.equal(motion.waiters.size,0);
assert.equal(motion.active,null);
motion.reduced=true;
events.length=0;
await motion.play('character.evolve',{characterId:'aquarius',fromLevel:3,toLevel:4});
assert.deepEqual(events.filter(x=>x.name==='complete').map(x=>x.motion),['character.evolve']);
assert.match(motion.characterEl.src,/idle\/aquarius_lv4.gif$/);
assert.equal(motion.waiters.size,0);
motion.destroy();
console.log('PASS: cấp tối đa; hủy tiến hóa cũ; idle cấp mới; dọn timer khi đổi hiệu ứng');
